#include "Arduino.h"
#include "ThinGyanMoe.h"
ThinGyanMoe::ThinGyanMoe(int Buzzpin){
_buzzpin = Buzzpin;
pinMode(_buzzpin,OUTPUT);
}
void ThinGyanMoe :: playThinGyanMoe(){
int melody[] = {
    NOTE_G4, NOTE_G4, NOTE_F4, NOTE_E4, NOTE_C4, //SO SO FA ME DO
    NOTE_C5, NOTE_C5, NOTE_B4, NOTE_A4, // DO DO TI LA
    NOTE_G4, NOTE_G4, NOTE_F4, NOTE_E4, NOTE_C4, NOTE_D4,//SO SO FA ME DO RE
    NOTE_G4, NOTE_G4, NOTE_F4, NOTE_E4, NOTE_C4, //SO SO FA ME DO
    NOTE_C5, NOTE_C5, NOTE_B4, NOTE_A4, // DO DO TI LA
    NOTE_G4, NOTE_G4, NOTE_A4, NOTE_G4, NOTE_E4, //SO LA SO ME
    NOTE_D4, NOTE_D4, NOTE_D4, NOTE_E4, NOTE_F4, NOTE_D4, NOTE_E4, //RE RE RE ME FA RE ME
    NOTE_C5, NOTE_C5, NOTE_B4, NOTE_A4, // DO DO TI LA
    NOTE_G4, NOTE_G4, NOTE_A4, NOTE_G4, NOTE_E4, //SO LA SO ME
    NOTE_D4, NOTE_D4, NOTE_D4, NOTE_E4, NOTE_F4, NOTE_B3, NOTE_C4, //RE RE RE ME FA TI DO
      
    NOTE_C5, NOTE_C5, NOTE_C5, NOTE_C5, NOTE_D5, NOTE_C5, NOTE_B4, NOTE_A4, NOTE_G4, NOTE_E4, //DO DO DO DO RE DO TI LA SO ME
    NOTE_F4, NOTE_F4, NOTE_F4, NOTE_F4, NOTE_G4, NOTE_F4, NOTE_E4, NOTE_D4, NOTE_E4, //FA FA FA FA SO FA ME RE ME
    
    NOTE_C5, NOTE_C5, NOTE_C5, NOTE_C5, NOTE_D5, NOTE_C5, NOTE_B4, NOTE_A4, NOTE_G4, NOTE_E4, //DO DO DO DO RE DO TI LA SO ME
    NOTE_F4, NOTE_F4, NOTE_F4, NOTE_F4, NOTE_G4, NOTE_F4, NOTE_E4, NOTE_D4, NOTE_E4, //FA FA FA FA SO FA ME RE ME
    
    NOTE_G4, NOTE_G4, NOTE_F4, NOTE_E4, NOTE_C4, //SO SO FA ME DO
    NOTE_C5, NOTE_C5, NOTE_B4, NOTE_A4, // DO DO TI LA
    NOTE_G4, NOTE_G4, NOTE_A4, NOTE_G4, NOTE_E4, //SO LA SO ME
    NOTE_D4, NOTE_D4, NOTE_D4, NOTE_E4, NOTE_F4, NOTE_B3, NOTE_C4 //RE RE RE ME FA TI DO
  };

int tempo[] = {
    QUARTER, EIGHTH, EIGHTH, QUARTER, QUARTER, //SO SO FA ME DO
    QUARTER, EIGHTH, EIGHTH, MINIM,// DO DO TI LA
    QUARTER, EIGHTH, EIGHTH, QUARTER, QUARTER, SEMIBREVE,//SO SO FA ME DO RE
    QUARTER, EIGHTH, EIGHTH, QUARTER, QUARTER, //SO SO FA ME DO
    QUARTER, EIGHTH, EIGHTH, MINIM,// DO DO TI LA
    QUARTER, EIGHTH, EIGHTH, QUARTER, QUARTER, //SO LA SO ME
    EIGHTH, EIGHTH, EIGHTH, EIGHTH, QUARTER, QUARTER, SEMIBREVE, //RE RE RE ME FA RE ME
    QUARTER, EIGHTH, EIGHTH, MINIM,// DO DO TI LA
    QUARTER, EIGHTH, EIGHTH, QUARTER, QUARTER, //SO LA SO ME
    EIGHTH, EIGHTH, EIGHTH, EIGHTH, QUARTER, QUARTER, SEMIBREVE, //RE RE RE ME FA TI DO
    
    EIGHTH, EIGHTH, EIGHTH, EIGHTH, EIGHTH, EIGHTH, EIGHTH, EIGHTH, MINIM, MINIM, //DO DO DO DO RE DO TI LA SO ME
    EIGHTH, EIGHTH, EIGHTH, EIGHTH, EIGHTH, EIGHTH, EIGHTH, EIGHTH, SEMIBREVE, //FA FA FA FA SO FA ME RE ME
    
    EIGHTH, EIGHTH, EIGHTH, EIGHTH, EIGHTH, EIGHTH, EIGHTH, EIGHTH, MINIM, MINIM, //DO DO DO DO RE DO TI LA SO ME
    EIGHTH, EIGHTH, EIGHTH, EIGHTH, EIGHTH, EIGHTH, EIGHTH, EIGHTH, SEMIBREVE, //FA FA FA FA SO FA ME RE ME

    QUARTER, EIGHTH, EIGHTH, QUARTER, QUARTER, //SO SO FA ME DO
    QUARTER, EIGHTH, EIGHTH, MINIM,// DO DO TI LA
    QUARTER, EIGHTH, EIGHTH, QUARTER, QUARTER, //SO LA SO ME
    EIGHTH, EIGHTH, EIGHTH, EIGHTH, QUARTER, QUARTER, SEMIBREVE //RE RE RE ME FA TI DO
  };

int size = sizeof(melody) / sizeof(int);
  
  for (int thisNote = 0; thisNote < size; thisNote++) {
    int noteDuration = 1000 / tempo[thisNote];
    int pauseBetweenNotes = noteDuration * 1.3;
    
    if (melody[thisNote] == 0) {
      noTone(_buzzpin);
      delay(pauseBetweenNotes);
    } else {
      tone(_buzzpin, melody[thisNote], noteDuration);
      delay(pauseBetweenNotes);
    }
  }
  noTone(_buzzpin);
}

